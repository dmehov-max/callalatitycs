# Критериите Ситуация 1/2/3 изискват РЕАЛНО дадена цена в разговора —
# ако price_delivery_silence е неприложим (Claude е решил, че цена не е
# давана), тези три НЕ могат да бъдат приложими, независимо какво е
# върнал Claude за тях поотделно. Проверявано на ниво КОД, не само чрез
# инструкция в промпта — LLM понякога не спазва тази връзка консистентно.
PRICE_GATED_CRITERIA = {"positive_scenario_closing", "price_objection_handling",
                         "soft_decline_probing"}


def _get_final_applicable_keys(criteria_scores: dict, call_type: str) -> set[str]:
    """
    Комбинира сигнали за приложимост на критерий в КОНКРЕТНИЯ разговор:
      1. call_type ограничение от criteria_config.py (напр. needs_discovery
         важи само за 'пълна_консултация') — контролирано от НАС в кода.
      2. ситуационна преценка от самия Claude ('applicable' полето) — за
         взаимно изключващите се Ситуация 1/2/3 критерии, само тази, която
         реално се е случила в разговора, остава приложима.
      3. ЦЕНОВО ограничение (код, не промпт): Ситуация 1/2/3 изискват
         price_delivery_silence да е ПРИЛОЖИМ (т.е. цена реално е била
         дадена) — иначе трите се форсират на неприложими, независимо
         какво е решил Claude поотделно за тях.
    Критерий участва в крайната оценка САМО ако ВСИЧКИ сигнали са True.
    """
    call_type_allowed = {c["key"] for c in get_applicable_criteria(call_type)}
    price_was_given = criteria_scores.get("price_delivery_silence", {}).get("applicable", True)

    final = set()
    for key in call_type_allowed:
        if not criteria_scores[key].get("applicable", True):
            continue
        if key in PRICE_GATED_CRITERIA and not price_was_given:
            continue  # форсирано неприложим - няма дадена цена в разговора
        final.add(key)
    return final


def _compute_overall_score(criteria_scores: dict, call_type: str) -> float:
    """
    Претеглена средна оценка, но САМО от критериите, приложими за ТОЗИ
    КОНКРЕТЕН разговор (и по call_type, и по ситуационна преценка от
    Claude) — теглата на приложимите критерии се пренормализират да
    сумират до 1.0.

    ИСТОРИЧЕСКА БЕЛЕЖКА: по-рано тук имаше механизъм за "минимален праг"
    на общото тегло (запълване с неутрална стойност 5, ако приложимите
    критерии бяха под определен праг) — добавен специално заради
    критерия 'opening_greeting' (Откриване), който имаше екстремна 1-10
    скала и беше уязвим на транскрибационни грешки. Този критерий беше
    премахнат изцяло от системата за оценяване (стана отделен, неоценяван
    индикатор 'korekt_mentioned') — затова прагът вече няма предпазна
    функция и беше премахнат. Останалите критерии са пълноценни, надеждни
    преценки — чистата пренормализация е правилният подход за тях.
    """
    final_keys = _get_final_applicable_keys(criteria_scores, call_type)

    if not final_keys:
        # Крайно рядък edge case (напр. абсурдно кратък/неразбираем разговор,
        # където Claude маркира почти всичко като неприложимо) — вместо
        # деление на нула, връщаме проста средна от всички налични оценки.
        all_scores = [criteria_scores[c["key"]]["score"] for c in CRITERIA]
        return round(sum(all_scores) / len(all_scores), 2)

    applicable_criteria = [c for c in CRITERIA if c["key"] in final_keys]
    weight_sum = sum(c["weight"] for c in applicable_criteria)

    weighted_total = sum(
        criteria_scores[c["key"]]["score"] * c["weight"] for c in applicable_criteria
    )
    return round(weighted_total / weight_sum, 2)


def _should_flag(criteria_scores: dict, overall_score: float, call_type: str) -> tuple[bool, str]:
    """Проверява праговете САМО за критериите, приложими за ТОЗИ разговор."""
    applicable_keys = _get_final_applicable_keys(criteria_scores, call_type)
    reasons = []

    if overall_score < ALERT_RULES["min_overall_score"]:
        reasons.append(
            f"общ резултат {overall_score} под праг {ALERT_RULES['min_overall_score']}"
        )

    for key, data in criteria_scores.items():
        if key not in applicable_keys:
            continue
        if data["score"] < ALERT_RULES["min_any_criterion_score"]:
            label = next(c["label"] for c in CRITERIA if c["key"] == key)
            reasons.append(f"'{label}' = {data['score']} (под минимален праг)")

    for key in ALERT_RULES["critical_criteria"]:
        if key not in applicable_keys:
            continue
        score = criteria_scores[key]["score"]
        if score < ALERT_RULES["critical_criteria_threshold"]:
            label = next(c["label"] for c in CRITERIA if c["key"] == key)
            reasons.append(f"критичен критерий '{label}' = {score}")

    return (len(reasons) > 0, "; ".join(reasons))


def analyze_transcript(transcript_text: str, call_metadata: dict = None,
                        secondary_transcript: str = None,
                        tertiary_transcript: str = None) -> dict:
    """
    Анализира един транскрипт.

    secondary_transcript, tertiary_transcript: опционални ДОПЪЛНИТЕЛНИ
    транскрипти на СЪЩОТО аудио, от различни модели за разпознаване на
    реч (напр. gpt-4o-mini-transcribe, whisper-1, gpt-4o-transcribe).
    Ако са подадени, Claude сравнява всички налични версии и съставя
    обединен, по-точен транскрипт, преди да анализира — особено полезно
    при кратки/шумни записи, където отделен модел може да "халюцинира"
    (повтори фраза безсмислено) на труден пасаж; наличието на 3 независими
    версии дава по-силен сигнал кое е правилното чрез съгласие между тях.
    Струва пропорционално повече транскрибационна цена (2x или 3x), без
    допълнителен реален разход за самия анализ (все още 1 Claude заявка).

    Връща dict с ключове: call_category, category_reasoning,
    diarized_transcript, overall_score,
    overall_summary, is_flagged, flag_reason, criteria_scores, cost_usd,
    model, raw_response.

    ВАЖНО: ако call_category == 'нерелевантен', is_flagged винаги е False
    (разговорът не е "лош", просто не е приложим за оценка) и не влиза в
    статистиките нагоре по веригата (Excel/dashboard филтрират по това поле).
    """
    tool = _build_tool_schema()

    criteria_list_text = "\n".join(
        f"- {c['label']} ({c['key']}, тегло {c['weight']}): {c['description']}"
        for c in CRITERIA
    )

    meta_text = ""
    if call_metadata:
        meta_text = f"\nМетаданни за разговора: {json.dumps(call_metadata, ensure_ascii=False)}\n"

    if secondary_transcript and tertiary_transcript:
        transcript_section = f"""Транскрипт А (модел 1):
---
{transcript_text}
---

Транскрипт Б (модел 2, същото аудио):
---
{secondary_transcript}
---

Транскрипт В (модел 3, същото аудио):
---
{tertiary_transcript}
---

Сравни ТРИТЕ транскрипта и състави ЕДИН обединен, най-точен транскрипт
(по правилата от системната инструкция), преди да анализираш разговора."""
    elif secondary_transcript:
        transcript_section = f"""Транскрипт А (модел 1):
---
{transcript_text}
---

Транскрипт Б (модел 2, същото аудио):
---
{secondary_transcript}
---

Сравни двата транскрипта и състави ЕДИН обединен, най-точен транскрипт
(по правилата от системната инструкция), преди да анализираш разговора."""
    else:
        transcript_section = f"""Транскрипт на разговора:
---
{transcript_text}
---"""

    user_message = f"""Ето критериите, по които трябва да оцениш разговора (освен ако не е 'нерелевантен'):

{criteria_list_text}
{meta_text}
{transcript_section}

Подай анализа чрез tool call-а submit_call_analysis."""

    response = client.messages.create(
        model=MODEL,
        max_tokens=2500,
        system=SYSTEM_PROMPT,
        tools=[tool],
        tool_choice={"type": "tool", "name": "submit_call_analysis"},
        messages=[{"role": "user", "content": user_message}],
    )

    tool_use_block = next(
        b for b in response.content if b.type == "tool_use"
    )
    result = tool_use_block.input

    overall_score = _compute_overall_score(result["criteria"], result["call_type"])
    is_flagged, flag_reason = _should_flag(result["criteria"], overall_score, result["call_type"])

    # Нерелевантните разговори никога не се флагват - не са "лош разговор",
    # просто не са приложими за оценка на служителя.
    if result["call_category"] == "нерелевантен":
        is_flagged = False
        flag_reason = None

    input_tokens = response.usage.input_tokens
    output_tokens = response.usage.output_tokens
    cost = round(
        (input_tokens / 1_000_000) * PRICE_INPUT_PER_M
        + (output_tokens / 1_000_000) * PRICE_OUTPUT_PER_M,
        6,
    )

    final_applicable_keys = _get_final_applicable_keys(result["criteria"], result["call_type"])
    criteria_scores_list = [
        {
            "key": c["key"],
            "label": c["label"],
            "score": result["criteria"][c["key"]]["score"],
            "justification": result["criteria"][c["key"]]["justification"],
            "applicable": c["key"] in final_applicable_keys,
        }
        for c in CRITERIA
    ]

    return {
        "korekt_mentioned": result["korekt_mentioned"],
        "referral_source_asked": result["referral_source_asked"],
        "service_line": result["service_line"],
        "followup_call_required": result["followup_call_required"],
        "call_category": result["call_category"],
        "category_reasoning": result["category_reasoning"],
        "call_type": result["call_type"],
        "call_type_reasoning": result["call_type_reasoning"],
        "diarized_transcript": result["diarized_transcript"],
        "agent_name": result["agent_name"],
        "agent_name_confidence": result["agent_name_confidence"],
        "overall_score": overall_score,
        "overall_summary": result["overall_summary"],
        "is_flagged": is_flagged,
        "flag_reason": flag_reason,
        "criteria_scores": criteria_scores_list,
        "cost_usd": cost,
        "model": MODEL,
        "raw_response": result,
    }


