"""
vocabulary_hints.py — Термини/кратки фрази, които подпомагат Whisper да
разпознава по-точно собствени имена и фирмени термини.

КАК ДА ГО РЕДАКТИРАШ:
Добавяй нови думи/кратки фрази в списъка VOCABULARY_PHRASES по-долу, всеки
път когато забележиш системна грешка в транскрипцията при конкретна дума
(напр. клиентът каза "Х", но Whisper системно го чува като "Y"). Пример:

  VOCABULARY_PHRASES = [
      "Корект",
      "преместване за домът и офиса",
      "пералня, хладилник, диван, мебели",
      ...
  ]

ВАЖНО ОГРАНИЧЕНИЕ: OpenAI Whisper API (модел whisper-1) приема prompt от
МАКСИМУМ 224 токена — ако списъкът стане по-дълъг, частта, която не се
събира, се ИГНОРИРА ТИХОМЪЛКОМ (без грешка). Затова:
  - Дръж списъка с КРАТКИ термини/фрази, не пълни изречения.
  - Приоритизирай РЕАЛНО объркваните думи (собствени имена, специфични
    термини), не общи думи, които моделът и без това разпознава добре.
  - Функцията build_hint() по-долу автоматично съкращава при нужда, но
    по-добре е списъкът да си остане разумен по обем от самото начало.
"""

VOCABULARY_PHRASES = [
    "Корект",
    "преместване за домът и офиса",
    "пералня",
    "хладилник",
    "диван",
    "мебели",
    "кашони",
    "офис адрес",
    "товарене",
    "разтоварване",
    "автомобил",
    "шофьор",
    "колегите ще дойдат",
    "ще пристигнат до половин час",
    "ще пристигнат до час",
    "адрес за товарене",
    "адрес за разтоварване",
    "дата и час на преместването",
]

# Груба апроксимация: ~4 символа ≈ 1 токен за латиница; за кирилица
# съотношението е по-неблагоприятно (обикновено по-малко символи на
# токен), затова пазим консервативен таван от символи, не токени.
MAX_HINT_CHARS_WHISPER_1 = 600       # твърд лимит на whisper-1 (224 токена)
MAX_HINT_CHARS_GPT4O_MINI = 1500     # по-щедро, но все пак разумно ограничение


def build_hint(model: str = "gpt-4o-mini-transcribe") -> str:
    """
    Съставя vocabulary hint низа от VOCABULARY_PHRASES, съобразен с
    лимита на конкретния модел. Ако списъкът стане прекалено дълъг с
    времето, тази функция пази последните (най-скоро добавени) фрази —
    приемаме, че по-новите добавки отразяват по-актуални проблеми.
    """
    full_hint = ". ".join(VOCABULARY_PHRASES) + "."

    limit = MAX_HINT_CHARS_WHISPER_1 if model == "whisper-1" else MAX_HINT_CHARS_GPT4O_MINI

    if len(full_hint) <= limit:
        return full_hint

    # Съкращаваме от НАЧАЛОТО, пазим края (най-новите фрази в списъка),
    # защото whisper-1 официално пази само последните токени на prompt-а.
    truncated = full_hint[-limit:]
    # Изрязваме до началото на първата пълна фраза, за да не режем дума наполовина.
    first_period = truncated.find(". ")
    if first_period != -1:
        truncated = truncated[first_period + 2:]
    return truncated
